export type TimetableOptions = z.infer<typeof TimetableOptionsSchema>;

export const TimetableVersionListSchema = z.object({ items: z.array(TimetableVersionViewSchema) });
export type TimetableVersionList = z.infer<typeof TimetableVersionListSchema>;

export const TimetableSectionListSchema = z.object({ items: z.array(TimetableSectionRefSchema) });
export type TimetableSectionList = z.infer<typeof TimetableSectionListSchema>;

/**
 * Phase 7 foundation — the lessons a teacher has on a calendar date, from the published timetable.
 * Each lesson carries the full attendance context: Date + Period + Class/Section + Subject + Teacher.
 */
export const TimetableLessonSchema = z.object({
  date: z.string(),
  day: Weekday.schema,
  period: TimetablePeriodViewSchema,
  entry: TimetableEntryViewSchema,
  versionId: z.string(),
});
export const TimetableLessonsViewSchema = z.object({
  date: z.string(),
  day: Weekday.schema,
  academicYear: TimetableYearRefSchema.nullable(),
  /** False when the date is outside every academic year or not a working day. */
  schoolDay: z.boolean(),
  lessons: z.array(TimetableLessonSchema),
});
export type TimetableLessonsView = z.infer<typeof TimetableLessonsViewSchema>;

/** Day of week of a 'YYYY-MM-DD' calendar date (no time zone involved). */
export function weekdayOf(date: string): Weekday {
  const [y, m, d] = date.split('-').map(Number) as [number, number, number];
  const index = new Date(Date.UTC(y, m - 1, d)).getUTCDay(); // 0 = Sunday
  return (['SUN', 'MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT'] as const)[index]!;
}
