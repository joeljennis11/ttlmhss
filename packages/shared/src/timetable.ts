import { z } from 'zod';
import {
  AcademicYearStatus,
  PeriodKind,
  RecordStatus,
  TimetableStatus,
  Weekday,
} from './controlled-values.js';
import { IdSchema, IsoDateSchema } from './validation.js';

/*
 * Phase 6 — Timetable contracts.
 *
 * Two different relationships — never confuse them:
 *   Teacher → Subject (Phase 5, `teacher_subjects`): what a teacher CAN teach. No class, no period.
 *   Timetable entry (Phase 6): Teacher + Subject + Class/Section + Day + Period, in one timetable
 *   VERSION of one academic year. This is the only place a teacher meets a class.
 *
 * Versions: each academic year has at most one DRAFT (being edited) and one PUBLISHED (live)
 * version; publishing turns the draft into the published version and the previous published
 * version into SUPERSEDED history. Class, teacher and student timetables — and, from Phase 7, the
 * attendance context (Date + Period + Class/Section + Subject + Teacher) — are all derived from the
 * PUBLISHED version. Nothing is stored twice.
 */

const WeekdaySchema = z.enum(Weekday.values, { message: 'Choose a day' });
const ref = (message: string) => z.string({ message }).pipe(IdSchema);

// ---- Editing the draft -------------------------------------------------------------------------

/**
 * One change to the draft. Changes are applied in order inside one transaction; any failure
 * rejects the whole batch (nothing is half-applied). `create.id` is generated by the client so
 * later changes in the same batch can refer to it; the API still validates it.
 */
export const TimetableOperationSchema = z.discriminatedUnion('op', [
  z.object({
    op: z.literal('create'),
    id: IdSchema,
    day: WeekdaySchema,
    periodId: ref('Choose a period'),
    sectionId: ref('Choose a class and section'),
    subjectId: ref('Choose a subject'),
    teacherId: ref('Choose a teacher'),
  }),
  z.object({
    op: z.literal('update'),
    entryId: IdSchema,
    subjectId: ref('Choose a subject'),
    teacherId: ref('Choose a teacher'),
  }),
  z.object({
    op: z.literal('move'),
    entryId: IdSchema,
    day: WeekdaySchema,
    periodId: ref('Choose a period'),
  }),
  z.object({ op: z.literal('remove'), entryId: IdSchema }),
]);
export type TimetableOperation = z.infer<typeof TimetableOperationSchema>;

export const TIMETABLE_BATCH_MAX = 300;

export const TimetableChangesSchema = z.object({
  /** The section whose editor view is returned. */
  sectionId: IdSchema,
  operations: z
    .array(TimetableOperationSchema)
    .min(1, { message: 'There are no changes to save' })
    .max(TIMETABLE_BATCH_MAX, { message: `Save at most ${TIMETABLE_BATCH_MAX} changes at once` }),
  /** Validate only: run every check against the draft, then roll back. Nothing is stored. */
  dryRun: z.boolean().default(false),
});
export type TimetableChangesInput = z.input<typeof TimetableChangesSchema>;

export const TimetableSectionQuerySchema = z.object({ sectionId: IdSchema });
export const TimetableYearQuerySchema = z.object({ academicYearId: IdSchema.optional() });
export const TimetableLessonsQuerySchema = z.object({
  date: IsoDateSchema,
  teacherId: IdSchema.optional(),
});

// ---- Views -------------------------------------------------------------------------------------

